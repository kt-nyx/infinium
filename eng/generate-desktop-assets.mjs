import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const compiledRoot = resolve(root, "artifacts/desktop-assets-compiled");
const assetRoot = resolve(root, "src/Infinium.DesktopHost/Assets");
const check = process.argv.includes("--check");
const rendererSource = JSON.parse(readFileSync(resolve(root, "contracts/json-schema/renderer-envelope.v1.schema.json"), "utf8"));
const compiledAssets = [
  "desktop-renderer.js",
  "bounded-result-pager.js",
  "client.js",
  "decoders.js",
  "schema-validator.js",
  "generated/renderer-contract.generated.js",
];
for (const path of compiledAssets) {
  const expected = readFileSync(resolve(compiledRoot, path));
  const destination = resolve(assetRoot, path);
  if (check) {
    if (!expected.equals(readFileSync(destination))) throw new Error(`Packaged desktop asset is stale: ${path}`);
  } else {
    mkdirSync(resolve(destination, ".."), { recursive: true });
    writeFileSync(destination, expected);
  }
}
const assetPaths = [
  "index.html", "app.css", ...compiledAssets,
  "vendor/react.production.min.js", "vendor/react-dom.production.min.js",
].sort();
const manifest = {
  schema: "infinium.desktop-assets/v1",
  renderer_registry_version: rendererSource["x-infinium-registry"].schema_version,
  assets: assetPaths.map((path) => {
    const bytes = readFileSync(resolve(assetRoot, path));
    return { path, bytes: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") };
  }),
};
const manifestBytes = `${JSON.stringify(manifest, null, 2)}\n`;
const manifestPath = resolve(assetRoot, "asset-manifest.json");
const manifestSha256 = createHash("sha256").update(manifestBytes, "utf8").digest("hex");
const catalogBytes = `// <auto-generated />\nnamespace Infinium.DesktopHost;\n\ninternal static class DesktopAssetCatalog\n{\n    internal const string ManifestSha256 = "${manifestSha256}";\n    internal const string RendererRegistryVersion = "${manifest.renderer_registry_version}";\n}\n`;
const catalogPath = resolve(root, "src/Infinium.DesktopHost/DesktopAssetCatalog.Generated.cs");
if (check) {
  if (readFileSync(manifestPath, "utf8").replaceAll("\r\n", "\n") !== manifestBytes) throw new Error("Packaged desktop asset manifest is stale.");
  if (readFileSync(catalogPath, "utf8").replaceAll("\r\n", "\n") !== catalogBytes) throw new Error("Compiled desktop asset catalog is stale.");
} else {
  writeFileSync(manifestPath, manifestBytes, "utf8");
  writeFileSync(catalogPath, catalogBytes, "utf8");
}
